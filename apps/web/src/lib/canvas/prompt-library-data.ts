async function loadYouMind(
  baseUrl: string,
  idPrefix: string,
  modelTag: string,
) {
  const markdown = await fetchText(baseUrl, "README_zh.md");
  const items: Array<Omit<LibraryPrompt, "category" | "githubUrl">> = [];
  for (const block of splitAtHeading(markdown, "### ")) {
    const title = matchFirst(block, /^###\s+No\.\s*\d+:\s*(.+)$/m).trim();
    const prompt = matchFirst(
      block,
      /#### .*?提示词\s*\r?\n\s*```[\w-]*\r?\n(.*?)\r?\n```/s,
    ).trim();
    if (!title || !prompt) continue;
    const images = markdownImages(baseUrl, block);
    const [, titlePrefix] = title.match(/^(.+?) - /) ?? [];
    items.push({
      id: `${idPrefix}-${padId(items.length + 1)}`,
      title,
      prompt,
      coverUrl: images[0] ?? "",
      tags: [modelTag, ...headingTags(titlePrefix ?? "")],
    });
  }
  return items;
}

async function loadDavidWu() {
  const raw = await fetchText(DAVIDWU_GPT_IMAGE2, "prompts.json");
  const data = JSON.parse(raw) as Array<{
    id?: number;
    title_en?: string;
    title_cn?: string;
    category?: string;
    category_cn?: string;
    prompt?: string;
    author?: string;
    source?: string;
    needs_ref?: boolean;
    image?: string;
  }>;
  const items: Array<Omit<LibraryPrompt, "category" | "githubUrl">> = [];
  for (const [index, item] of data.entries()) {
    const title = (item.title_cn || item.title_en || "").trim();
    const prompt = (item.prompt || "").trim();
    if (!title || !prompt) continue;
    const tags = splitTags(
      [item.category_cn, item.category, item.author, item.source]
        .filter(Boolean)
        .join("/"),
      /\//,
    );
    if (item.needs_ref) tags.push("需要参考图");
    items.push({
      id: `davidwu-gpt-image2-prompts-${padId(item.id ?? index + 1)}`,
      title,
      prompt,
      coverUrl: absoluteImageUrl(DAVIDWU_GPT_IMAGE2, item.image ?? ""),
      tags,
    });
  }
  return items;
}

// ── Parsing helpers (exported for tests) ──────────────────────────────────

async function fetchText(baseUrl: string, file: string): Promise<string> {
  const response = await fetch(`${baseUrl}/${file}`, { cache: "no-store" });
  if (!response.ok) throw new Error(`${file} 拉取失败`);
  return response.text();
}

/** Split markdown into blocks, each starting at a line with `prefix`. */
export function splitAtHeading(markdown: string, prefix: string): string[] {
  const blocks: string[] = [];
  let current: string[] = [];
  for (const line of markdown.split("\n")) {
    if (line.startsWith(prefix) && current.length > 0) {
      blocks.push(current.join("\n"));
      current = [];
    }
    current.push(line);
  }
  blocks.push(current.join("\n"));
  return blocks;
}

export function matchFirst(value: string, pattern: RegExp): string {
  return pattern.exec(value)?.[1] ?? "";
}

/**
 * All markdown image URLs in a block, made absolute against the repo base.
 * Badge/shield images (repo decoration, not prompt covers) are dropped —
 * without this, blocks that open with a shields.io badge get a badge as
 * their card cover.
 */
export function markdownImages(baseUrl: string, markdown: string): string[] {
  return Array.from(markdown.matchAll(/!\[[^\]]*]\(([^)]+)\)/g), (match) =>
    absoluteImageUrl(baseUrl, match[1] ?? ""),
  ).filter((url) => url !== "" && !isBadgeImage(url));
}

/** True for badge/shield decoration images that must not be used as covers. */
export function isBadgeImage(url: string): boolean {
  return /img\.shields\.io|badge\.fury\.io|\/badge\//i.test(url);
}

/**
 * Hosts whose covers the controller cover-cache proxy will fetch. Everything
 * the five sources actually reference today; anything else is served direct
 * from its origin (and falls back to the placeholder on error).
 */
export function isProxyableCoverUrl(url: string): boolean {
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "https:") return false;
    // pbs.twimg.com is deliberately NOT proxied: it is frequently unreachable
    // from the controller's network, and a hanging proxied fetch occupies one
    // of the browser's ~6 connections to OUR origin — a page of covers can
    // starve every other cover/probe request into an endless blank pending
    // state. Loaded direct, a twimg failure stays on twitter's origin pool.
    return (
      parsed.hostname === "github.com" ||
      parsed.hostname.endsWith(".githubusercontent.com")
    );
  } catch {
    return false;
  }
}

/**
 * The <img src> for a cover: proxyable hosts route through the controller's
 * disk-backed cover cache (served from OUR server, one upstream fetch per
 * image ever); other hosts load direct. Returns "" for no cover.
 */
export function promptCoverPath(coverUrl: string): string {
  if (!coverUrl) return "";
  if (!isProxyableCoverUrl(coverUrl)) return coverUrl;
  return `/api/v1/media/prompt-cover?url=${encodeURIComponent(coverUrl)}`;
}

export function absoluteImageUrl(baseUrl: string, image: string): string {
  if (!image) return "";
  if (/^https?:\/\//i.test(image)) return image;
  return `${baseUrl}/${image.replace(/^\.?\//, "")}`;
}

/** Tags from a section heading: strip decoration, split on /&、与. */
export function headingTags(heading: string): string[] {
  return splitTags(
    heading.replace(/[^\p{L}\p{N}/&、与 ]/gu, ""),
    /\s*(?:\/|&|、|与)\s*/,
  );
}

export function splitTags(value: string, pattern: RegExp): string[] {
  return value
    .split(pattern)
    .map((tag) => tag.trim().toLowerCase())
    .filter(Boolean);
}

function padId(value: number): string {
  return String(value).padStart(4, "0");
}

/** Test-only: clear in-memory cache so fetch paths re-run. */
export function __resetPromptDataForTests(): void {
  memoryCache = null;
  memoryCacheAt = 0;
  inFlight = null;
}
