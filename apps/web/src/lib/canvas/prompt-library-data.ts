// ── Fetch orchestration + cache ────────────────────────────────────────────
//
// Freshness ladder:
//   1. memory / localStorage cache within TTL → serve as-is
//   2. stale cache OR nothing → serve IMMEDIATELY (stale cache, else the
//      bundled snapshot) and kick off a background refresh — opening the
//      dialog never blocks on GitHub fetches
//   3. refreshed data lands in the caches; the next query serves it

/** Built-in baseline (generated by apps/web/scripts/generate-prompt-snapshot.ts). */
const SNAPSHOT: LibraryPrompt[] = bundledSnapshot as LibraryPrompt[];

let memoryCache: LibraryPrompt[] | null = null;
let memoryCacheAt = 0;
let inFlight: Promise<LibraryPrompt[]> | null = null;

async function getAllPrompts(): Promise<LibraryPrompt[]> {
  const now = Date.now();
  if (memoryCache && now - memoryCacheAt < CACHE_TTL_MS) return memoryCache;

  const stored = readStoredCache();
  if (stored) {
    memoryCache = stored.items;
    memoryCacheAt = stored.fetchedAt;
    if (now - stored.fetchedAt < CACHE_TTL_MS) return stored.items;
  }

  // Nothing fresh: refresh in the background, serve what we have right now.
  if (!inFlight) {
    inFlight = refreshFromSources().finally(() => {
      inFlight = null;
    });
  }
  if (stored) return stored.items;
  return SNAPSHOT;
}

async function refreshFromSources(): Promise<LibraryPrompt[]> {
  const live = await loadAllSources({ fallbackToSnapshot: false });
  // A total network failure yields []; don't poison the cache with it, so
  // the next open retries instead of serving an empty library for an hour.
  if (live.length === 0) return [];
  const items = promptCategories().flatMap((category) => {
    const refreshed = live.filter((item) => item.category === category);
    return refreshed.length > 0
      ? refreshed
      : SNAPSHOT.filter((item) => item.category === category);
  });
  memoryCache = items;
  memoryCacheAt = Date.now();
  writeStoredCache(items, memoryCacheAt);
  return items;
}

/**
 * Fetch + parse every source (exported for the snapshot generation script).
 * Failed sources keep their bundled entries. Snapshot generation disables
 * fallback so a fetch failure cannot masquerade as a successful update.
 */
export async function loadAllSources({
  categories = promptCategories(),
  fallbackToSnapshot = true,
}: { categories?: string[]; fallbackToSnapshot?: boolean } = {}): Promise<
  LibraryPrompt[]
> {
  const settled = await Promise.all(
    SOURCES.filter((source) => categories.includes(source.category)).map(
      async (source) => {
        try {
          const items = await source.load();
          if (items.length === 0) throw new Error("Empty prompt source");
          return items.map((item) => ({
            ...item,
            category: source.category,
            githubUrl: item.githubUrl ?? source.githubUrl,
          }));
        } catch {
          return fallbackToSnapshot
            ? SNAPSHOT.filter((item) => item.category === source.category)
            : [];
        }
      },
    ),
  );
  return settled.flat();
}

function readStoredCache(): {
  items: LibraryPrompt[];
  fetchedAt: number;
} | null {
  try {
    const raw = localStorage.getItem(CACHE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw) as {
      items?: LibraryPrompt[];
      fetchedAt?: number;
    };
    if (!Array.isArray(parsed.items) || typeof parsed.fetchedAt !== "number") {
      return null;
    }
    return { items: parsed.items, fetchedAt: parsed.fetchedAt };
  } catch {
    return null;
  }
}

function writeStoredCache(items: LibraryPrompt[], fetchedAt: number): void {
  try {
    localStorage.setItem(CACHE_KEY, JSON.stringify({ items, fetchedAt }));
  } catch {
    // Quota exceeded on a large payload — memory cache still covers the session.
  }
}

// ── Query API (dialog-facing) ──────────────────────────────────────────────

export async function fetchPromptPage({
  keyword = "",
  tags = [],
  category = ALL_PROMPTS_OPTION,
  page = 1,
  pageSize = 20,
}: {
  keyword?: string;
  tags?: string[];
  category?: string;
  page?: number;
  pageSize?: number;
} = {}): Promise<PromptPage> {
  const items = await getAllPrompts();
  const query = keyword.trim().toLowerCase();
  const safePage = Math.max(1, page);
  const safeSize = Math.max(1, Math.min(100, pageSize));
  // Tag options come from the keyword+category slice WITHOUT the tag filter,
  // so picking one tag doesn't collapse the tag cloud to itself.
  const scope = applyFilters(items, {
    keyword: query,
    category,
    tags: [],
    deduplicate: false,
  });
  const filtered = applyFilters(items, { keyword: query, category, tags });
  return {
    items: filtered.slice((safePage - 1) * safeSize, safePage * safeSize),
    tags: uniqueTags(scope),
    categories: promptCategories(),
    total: filtered.length,
  };
}

export function applyFilters(
  items: ReadonlyArray<LibraryPrompt>,
  options: {
    keyword: string;
    category: string;
    tags: string[];
    deduplicate?: boolean;
  },
): LibraryPrompt[] {
  const seen = new Set<string>();
  return items.filter((item) => {
    if (
      options.category &&
      options.category !== ALL_PROMPTS_OPTION &&
      item.category !== options.category
    ) {
      return false;
    }
    if (
      options.tags.length > 0 &&
      !options.tags.some((tag) => item.tags.includes(tag))
    ) {
      return false;
    }
    if (
      options.keyword &&
      ![item.title, item.prompt, item.category, ...item.tags]
        .join(" ")
        .toLowerCase()
        .includes(options.keyword)
    )
      return false;
    // Keep each collection intact; collapse identical prompts only in 全部.
    if (
      options.deduplicate !== false &&
      (!options.category || options.category === ALL_PROMPTS_OPTION)
    ) {
      const key = item.prompt.trim().replace(/\s+/g, " ");
      if (seen.has(key)) return false;
      seen.add(key);
    }
    return true;
  });
}

function uniqueTags(items: ReadonlyArray<LibraryPrompt>): string[] {
  return Array.from(new Set(items.flatMap((i) => i.tags).filter(Boolean)));
}

