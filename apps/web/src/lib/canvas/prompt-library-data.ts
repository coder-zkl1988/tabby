/**
 * prompt-library-data.ts — third-party prompt library loader.
 *
 * Pulls curated image-generation prompts from public GitHub collections,
 * parses each repo's README or structured JSON into typed
 * entries, and serves keyword/category/tag-filtered pages to the dialog.
 *
 * Caching: parsed items go to versioned localStorage
 * with a 1-hour TTL; oversized/quota failures degrade silently to
 * per-session memory. Unreachable sources retain their bundled baseline.
 */

import bundledSnapshot from "./prompt-library-snapshot.json";

export type LibraryPrompt = {
  id: string;
  title: string;
  coverUrl: string;
  prompt: string;
  tags: string[];
  category: string;
  githubUrl: string;
  sourceLabel?: string;
  sourceUrl?: string;
};

export type PromptPage = {
  items: LibraryPrompt[];
  tags: string[];
  categories: string[];
  total: number;
};

export const ALL_PROMPTS_OPTION = "全部";

