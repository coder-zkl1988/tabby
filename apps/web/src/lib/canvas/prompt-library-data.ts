function httpUrl(value: unknown): string | undefined {
  if (typeof value !== "string") return undefined;
  try {
    const url = new URL(value);
    return url.protocol === "https:" || url.protocol === "http:"
      ? url.href
      : undefined;
  } catch {
    return undefined;
  }
}

/** cases.json uses website image paths; the actual files live in data/images. */
export function parseFreestyleflyCases(data: unknown): SourcePrompt[] {
  if (
    !data ||
    typeof data !== "object" ||
    !("cases" in data) ||
    !Array.isArray(data.cases)
  )
    return [];
  const items: SourcePrompt[] = [];
  const seen = new Set<number>();
  for (const row of data.cases as unknown[]) {
    if (!row || typeof row !== "object") continue;
    const item = row as Record<string, unknown>;
    if (
      typeof item.id !== "number" ||
      !Number.isSafeInteger(item.id) ||
      item.id <= 0 ||
      seen.has(item.id)
    )
      continue;
    const title = typeof item.title === "string" ? item.title.trim() : "";
    const prompt = typeof item.prompt === "string" ? item.prompt.trim() : "";
    if (!title || !prompt) continue;
    const category = typeof item.category === "string" ? item.category : "";
    const tags = [
      category ? (FREESTYLEFLY_CATEGORIES[category] ?? category) : "",
      "gpt-image-2",
    ];
    for (const values of [item.styles, item.scenes]) {
      if (!Array.isArray(values)) continue;
      tags.push(
        ...values
          .filter(
            (v): v is string => typeof v === "string" && Boolean(v.trim()),
          )
          .map((v) => v.trim().toLowerCase()),
      );
    }
    const image = typeof item.image === "string" ? item.image : "";
    // Restrict relative paths to the known repository image directory.
    const coverUrl = /^\/images\/[\w/-]+\.(?:jpg|jpeg|png|webp)$/i.test(image)
      ? `${FREESTYLEFLY_GPT_IMAGE_2}/data${image}`
      : (httpUrl(image) ?? "");
    items.push({
      id: `freestylefly-gpt-image-2-${padId(item.id)}`,
      title,
      prompt,
      coverUrl,
      tags: [...new Set(tags.filter(Boolean))],
      githubUrl: `${FREESTYLEFLY_REPO}/blob/main/docs/gallery-part-${item.id <= 165 ? 1 : 2}.md#case-${item.id}`,
      ...(typeof item.sourceLabel === "string"
        ? { sourceLabel: item.sourceLabel.trim() }
        : {}),
      ...(httpUrl(item.sourceUrl)
        ? { sourceUrl: httpUrl(item.sourceUrl) }
        : {}),
    });
    seen.add(item.id);
  }
  return items;
}

async function loadAwesomeGptImage() {
  const markdown = await fetchText(AWESOME_GPT_IMAGE, "README.zh-CN.md");
  const items: Array<Omit<LibraryPrompt, "category" | "githubUrl">> = [];
  for (const section of splitAtHeading(markdown, "## ")) {
    const tags = headingTags(matchFirst(section, /^##\s+(.+)$/m));
    for (const block of splitAtHeading(section, "### ")) {
      const title = matchFirst(block, /^###\s+(.+)$/m)
        .replace(/\[([^\]]+)]\([^)]+\)/g, "$1")
        .trim();
      const prompt = matchFirst(
        block,
        /\*\*提示词:\*\*\s*\r?\n\s*```[\w-]*\r?\n(.*?)\r?\n```/s,
      ).trim();
      if (!title || !prompt) continue;
      const images = markdownImages(AWESOME_GPT_IMAGE, block);
      items.push({
        id: `awesome-gpt-image-${padId(items.length + 1)}`,
        title,
        prompt,
        coverUrl: images[0] ?? "",
        tags,
      });
    }
  }
  return items;
}

